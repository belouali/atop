"""build_tables_only_docx, quick-review document with only the tables.

Generates ``AToP_JAMIA_tables_only.docx`` containing the four main-paper
tables plus Table S2, with their titles and legends and nothing else.
Each table is produced by the same function the manuscript builders use
(``add_table_1`` to ``add_table_4`` in build_revised_main_docx.py and
``add_table_s2`` in build_revised_supplement_docx.py), so the content
is identical by construction.

Usage:
    python paper/jamia2026/builders/build_tables_only_docx.py
"""
from __future__ import annotations

import os
import sys

sys.path.insert(0, os.path.dirname(__file__))
from _docx_helpers import new_document, title, para, page_break
from build_revised_main_docx import (
    add_table_1, add_table_2, add_table_3, add_table_4, SUBMISSION_DIR,
)
from build_revised_supplement_docx import add_table_s2

OUT_PATH = os.path.join(SUBMISSION_DIR, "AToP_JAMIA_tables_only.docx")


def build() -> None:
    doc = new_document()
    title(doc, "AToP JAMIA submission, tables for quick review")
    para(doc,
         "This document contains all main-paper tables (Tables 1-4) and "
         "Table S2 from the supplement, with their titles and legends, and "
         "nothing else. Each table is generated by the same code the "
         "manuscript uses, so content here matches the manuscript exactly.",
         italic=True)
    for fn in (add_table_1, add_table_2, add_table_3, add_table_4, add_table_s2):
        fn(doc)
        if fn is not add_table_s2:
            page_break(doc)
    os.makedirs(os.path.dirname(OUT_PATH), exist_ok=True)
    doc.save(OUT_PATH)
    print(f"\u2713 Wrote {OUT_PATH}")
    print(f"  Tables: {len(doc.tables)}")


if __name__ == "__main__":
    build()
